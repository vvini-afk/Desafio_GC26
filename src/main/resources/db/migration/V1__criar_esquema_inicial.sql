
CREATE TABLE cidade (
    id_cidade integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar NOT NULL,
    uf character(2) NOT NULL
);

CREATE TABLE hierarquia (
    id_hierarquia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_representante integer,
    nome_vendedor varchar NOT NULL
);

CREATE TABLE produto (
    id_item integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar NOT NULL,
    cod_familia varchar,
    preco_base numeric NOT NULL,
    preco_minimo numeric NOT NULL,
    ativo boolean DEFAULT true
);

CREATE TABLE cliente (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj varchar UNIQUE,
    nome varchar NOT NULL,
    segmento varchar,
    subsegmento varchar,
    numero_celular varchar,
    cep character(8),
    ultima_compra timestamp without time zone,
    id_hierarquia integer,
    id_cidade integer,
    CONSTRAINT cliente_id_cidade_fkey
        FOREIGN KEY (id_cidade) REFERENCES cidade (id_cidade),
    CONSTRAINT cliente_id_hierarquia_fkey
        FOREIGN KEY (id_hierarquia) REFERENCES hierarquia (id_hierarquia)
);

CREATE TABLE estoque_erp (
    produto_id integer PRIMARY KEY,
    quantidade_disponivel integer NOT NULL DEFAULT 0,
    ultima_atualizacao timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT estoque_erp_produto_id_fkey
        FOREIGN KEY (produto_id) REFERENCES produto (id_item)
);

CREATE TABLE pedido (
    id_pedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_pedido timestamp without time zone NOT NULL,
    id_cliente integer,
    CONSTRAINT pedido_id_cliente_fkey
        FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

CREATE TABLE item_pedido (
    pedido_id integer NOT NULL,
    produto_id integer NOT NULL,
    quantidade integer NOT NULL,
    valor_unitario numeric NOT NULL,
    CONSTRAINT item_pedido_pkey PRIMARY KEY (pedido_id, produto_id),
    CONSTRAINT item_pedido_pedido_id_fkey
        FOREIGN KEY (pedido_id) REFERENCES pedido (id_pedido),
    CONSTRAINT item_pedido_produto_id_fkey
        FOREIGN KEY (produto_id) REFERENCES produto (id_item)
);

CREATE TABLE produto_complementar (
    produto_id integer NOT NULL,
    complementar_id integer NOT NULL,
    CONSTRAINT produto_complementar_pkey PRIMARY KEY (produto_id, complementar_id),
    CONSTRAINT produto_complementar_produto_id_fkey
        FOREIGN KEY (produto_id) REFERENCES produto (id_item),
    CONSTRAINT produto_complementar_complementar_id_fkey
        FOREIGN KEY (complementar_id) REFERENCES produto (id_item)
);

CREATE TABLE promocao (
    id_promocao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar NOT NULL,
    produto_id integer,
    categoria varchar,
    tipo_desconto varchar NOT NULL,
    valor_desconto numeric NOT NULL,
    inicio timestamp without time zone NOT NULL,
    fim timestamp without time zone NOT NULL,
    ativa boolean DEFAULT true,
    CONSTRAINT promocao_produto_id_fkey
        FOREIGN KEY (produto_id) REFERENCES produto (id_item)
);

CREATE TABLE notificacao (
    id_notificacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer,
    tipo varchar,
    mensagem text NOT NULL,
    canal varchar,
    status varchar,
    criada_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notificacao_cliente_id_fkey
        FOREIGN KEY (cliente_id) REFERENCES cliente (id_cliente)
);
